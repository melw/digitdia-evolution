"""gen_sig.py - write pldr/sig.h: FNV-1a hashes of the bootloader routines the patch-loader calls.

  python tools/gen_sig.py <8 MB flash dump>

The patch-loader checks these hashes in RAM before calling any bootloader routine. Only the hashes go into sig.h,
no bootloader code.
"""
import os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import flashdump  # noqa: E402

ROUTINES = [  # address, bytes hashed, what
    (0x8ff080b4, 0x58, 'I-cache invalidate (stage 1 tail)'),
    (0x8ff08110, 0x48, 'D-cache write-back + invalidate (stage 1 tail)'),
    (0x8ff0815c, 0x100, 'BCL LZ decompressor (stage 1 tail)'),
    (0x8ff0ca88, 0x4c, 'storage deinit'),
    (0x8ff0d408, 0x100, 'storage read'),
    (0x8ff0d984, 0x100, 'storage init'),
]


def fnv(words):
    h = 0x811c9dc5
    for w in words:
        h = ((h ^ w) * 16777619) & 0xffffffff
    return h


def ram_image(dump):
    """{base: bytes} of the bootloader as it sits in RAM when FWFS601T.BIN runs."""
    return {0x8ff08000: dump[flashdump.STAGE1_TAIL[0]:flashdump.STAGE1_TAIL[1]],
            0x8ff09000: flashdump.unbcl(dump, flashdump.LOADER_BODY)}


def read(ram, addr, n):
    for base, data in ram.items():
        if base <= addr and addr + n <= base + len(data):
            return data[addr - base:addr - base + n]
    raise ValueError('%#x not in the bootloader image' % addr)


def main():
    ram = ram_image(flashdump.load(sys.argv[1]))
    lines = ['/* generated by tools/gen_sig.py: FNV-1a (32-bit words) of the bootloader routines the patch-loader calls */',
             '#define NSIG %d' % len(ROUTINES)]
    hashes = []
    for addr, n, what in ROUTINES:
        b = read(ram, addr, n)
        hashes.append(fnv(struct.unpack('<%dI' % (n // 4), b)))
        lines.append('/* %#x +%#x %s */' % (addr, n, what))
    lines.append('static const u32 sig_addr[NSIG] = {%s};' % ', '.join('0x%08x' % r[0] for r in ROUTINES))
    lines.append('static const u32 sig_len[NSIG] = {%s};' % ', '.join('0x%x' % r[1] for r in ROUTINES))
    lines.append('static const u32 sig_hash[NSIG] = {%s};' % ', '.join('0x%08x' % h for h in hashes))
    out = os.path.join(HERE, '..', 'pldr', 'sig.h')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('pldr/sig.h written (%d routines)' % len(ROUTINES))


if __name__ == '__main__':
    main()

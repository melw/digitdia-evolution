"""make_pldr.py - build the patch-loader FWFS601T.BIN (our code + patch words only, no Reflecta code).

The patch-loader runs from the SD card, reads the scanner's own firmware from flash, checks that it is exactly
stock firmware 2.0, patches it in RAM and starts it as a normal flash boot. See pldr/README.md.

  python make_pldr.py
        build from the committed pldr/patches.h + pldr/sig.h. Needs only the mipsel toolchain, no firmware.
  python make_pldr.py --dump <flash dump>
        the same, plus the emulator tests against your flash dump (pip install unicorn)
  python make_pldr.py --regen out/rel2/fw.rbn --tag "FIRMWARE V2.0 PLV1.1"
        regenerate pldr/patches.h from an image made by build.py (needs base/fw_main.rbn). The noT patch words are
        dropped: the patch-loader hands over as a normal flash boot, which makes noT unnecessary.

Output: out/pldr/FWFS601T.BIN (copy it to the root of a FAT32 card).
"""
import argparse, hashlib, os, struct, subprocess, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PL = os.path.join(ROOT, 'pldr')
STOCK = os.path.join(ROOT, 'base', 'fw_main.rbn')
TAG_OFF = 0x80124a24 - 0x80000000
NOT_WORDS = [0x801dc108, 0x801dc2f4]          # src/patch_noT.py sites
LOAD, RELOC = 0x80000000, 0x8e000000
sys.path.insert(0, os.path.join(ROOT, 'src'))
import ntk  # noqa: E402


def run(cmd, cwd=ROOT):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('FAILED: %s\n%s%s' % (' '.join(cmd), r.stdout, r.stderr))
    return r.stdout


def sh(cmd):
    return run(['wsl', '-e', 'sh', '-c', cmd] if os.name == 'nt' else ['sh', '-c', cmd], PL)


def sha(b):
    return hashlib.sha256(b).hexdigest()


def regen(image, tag, keep_not):
    stock = open(STOCK, 'rb').read()
    tgt = bytearray(open(image, 'rb').read())
    assert len(tgt) == len(stock), 'image size differs from base/fw_main.rbn'
    if not keep_not:
        for v in NOT_WORDS:
            o = v - LOAD
            tgt[o:o + 4] = stock[o:o + 4]
    if tag:
        assert len(tag) == 20, 'tag must be exactly 20 characters'
        tgt[TAG_OFF:TAG_OFF + 20] = tag.encode()
    ntk.fix_image(tgt)
    W = struct.unpack('<%dI' % (len(stock) // 4), stock)
    T = struct.unpack('<%dI' % (len(tgt) // 4), bytes(tgt))
    patches = [(i * 4, t) for i, (w, t) in enumerate(zip(W, T)) if w != t]
    with open(os.path.join(PL, 'patches.h'), 'w') as f:
        f.write('/* generated by make_pldr.py --regen from %s; EXIF tag "%s" */\n' % (os.path.basename(image), tgt[TAG_OFF:TAG_OFF + 20].decode()))
        f.write('/* fingerprint of stock firmware 2.0: unpacked size and 32-bit word sum */\n')
        f.write('#define STOCK_SIZE 0x%xu\n#define STOCK_SUM 0x%08xu\n#define NPATCH %d\n' % (len(stock), sum(W) & 0xffffffff, len(patches)))
        f.write('static const u32 patch_off[NPATCH] = {%s};\n' % ', '.join('0x%x' % o for o, _ in patches))
        f.write('static const u32 patch_val[NPATCH] = {%s};\n' % ', '.join('0x%08x' % v for _, v in patches))
    print('pldr/patches.h: %d patch words, tag "%s"' % (len(patches), tgt[TAG_OFF:TAG_OFF + 20].decode()))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--regen', metavar='IMAGE', help='regenerate pldr/patches.h from this image (made by build.py)')
    ap.add_argument('--tag', help='with --regen: EXIF Software string, exactly 20 chars')
    ap.add_argument('--keep-noT', action='store_true', help='with --regen: keep the noT patch words')
    ap.add_argument('--dump', help='run the emulator tests against this 8 MB flash dump')
    a = ap.parse_args()
    if a.regen:
        regen(a.regen, a.tag, a.keep_noT)

    # compile + link
    sh('mipsel-linux-gnu-gcc -march=mips32r2 -EL -ffreestanding -nostdlib -fno-pic -mno-abicalls -G0 -Os '
       '-fno-builtin -Wall -c pldr.c -o pldr.o && '
       'mipsel-linux-gnu-gcc -march=mips32r2 -EL -fno-pic -mno-abicalls -G0 -c entry.S -o entry.o && '
       'mipsel-linux-gnu-ld -EL -T pldr.ld --no-dynamic-linker -o pldr.elf entry.o pldr.o && '
       'mipsel-linux-gnu-objcopy -O binary -j .text pldr.elf pldr.text')
    sym = {l.split()[2]: int(l.split()[0], 16) for l in sh('mipsel-linux-gnu-nm pldr.elf').splitlines() if len(l.split()) == 3}
    for line in sh('mipsel-linux-gnu-objdump -h pldr.elf').splitlines():
        p = line.split()
        if len(p) > 2 and p[1] == '.bss' and int(p[2], 16):
            sys.exit('.bss is not empty (it would not be in the image)')
    assert sym['_entry'] == RELOC + 0x100, hex(sym['_entry'])

    # image: header + code
    text = open(os.path.join(PL, 'pldr.text'), 'rb').read()
    img = bytearray(0x100) + text
    img += bytes(-len(img) % 4)
    assert len(img) == sym['_image_size'], (len(img), sym['_image_size'])
    struct.pack_into('<I', img, 0, LOAD + 0x100)                 # entry word: stage 1 jumps to *(0x80000000)
    img[0x50:0x68] = b'NT96660\x00' + b'10000000' + b'20100701'  # id layout as in the stock header
    struct.pack_into('<I', img, 0x68, len(img))                  # image size (checked by the bootloader)
    img[0x94:0x9c] = b'\xff' * 8                                 # as in stock (the bootloader overwrites it)
    ntk.fix_image(img)
    odir = os.path.join(ROOT, 'out', 'pldr')
    os.makedirs(odir, exist_ok=True)
    open(os.path.join(odir, 'pldr.rbn'), 'wb').write(img)
    print('patch-loader image: %d bytes' % len(img))

    if a.dump:
        print(run([sys.executable, os.path.join(ROOT, 'tools', 'emu_pldr.py'), os.path.join(odir, 'pldr.rbn'), a.dump]).strip())

    bcl = ntk.pack(img, 'patch-loader')
    out = os.path.join(odir, 'FWFS601T.BIN')
    open(out, 'wb').write(bcl)
    print('out/pldr/FWFS601T.BIN: %d bytes, SHA256 %s' % (len(bcl), sha(bcl)))


if __name__ == '__main__':
    main()
